const assert = require('node:assert/strict');

exports.run = async ({ page, selectFirm, firm, other, rpc, year }) => {
  const read = () => rpc('paperwork_accounting_workspace',{p_firm:firm,p_year:year});
  const before = await read();
  const panel = page.locator('details').filter({has:page.locator('summary').filter({hasText:'Poreska pravila i referentni primeri'})}).first();
  await panel.locator('summary').first().click();
  assert.equal(await panel.getByLabel('Poreski režim u primeru').inputValue(),'');
  await panel.getByLabel('Pravna forma u primeru').selectOption('doo');
  await panel.getByLabel('Poreski režim u primeru').selectOption('regular_vat');
  await panel.getByLabel('Dokaz režima za primer').fill('Synthetic VAT status evidence');
  await panel.getByLabel('Datum prometa u primeru').fill('2026-10-09');
  await panel.getByLabel('Osnovica primera RSD').fill('1000,00');
  const calculate=()=>panel.getByRole('button',{name:'Proveri poreski primer',exact:true}).click();
  const result=panel.getByRole('status',{name:'Rezultat poreskog primera'});
  await calculate(); await result.getByText(/PDV 200.00 RSD · Ukupno 1200.00 RSD/).waitFor();
  await panel.getByLabel('Poreska kategorija primera').selectOption('reduced');
  assert.equal(await result.count(),0); await calculate();
  await result.getByText('Potrebna poreska provera',{exact:true}).waitFor();
  await panel.getByLabel('Tačka člana 23 stav 2').selectOption('1');
  await panel.getByLabel('Dokaz klasifikacije',{exact:true}).fill('Synthetic bread classification');
  await panel.getByLabel('Smer primera').selectOption('purchase');
  await calculate(); await result.getByText(/PDV 100.00 RSD · Ukupno 1100.00 RSD/).waitFor();
  await result.getByText(/pravo na odbitak nije utvrđeno/).waitFor();
  await panel.getByLabel('Datum ranijeg avansa (ako postoji)').fill('2026-09-01');
  await calculate(); await result.getByText('Potrebna poreska provera',{exact:true}).waitFor();
  assert.equal(await result.getByText(/Ukupno/).count(),0);
  await panel.getByLabel('Datum ranijeg avansa (ako postoji)').fill('');
  await panel.getByLabel('Datum prometa u primeru').fill('2027-01-01');
  await calculate(); await result.getByText('Scenario nije podržan',{exact:true}).waitFor();
  assert.equal(await panel.getByRole('link',{name:'Zakon o PDV — Ministarstvo finansija'}).getAttribute('href'),'https://www.mfin.gov.rs/sr/propisi-1/zakon-o-porezu-na-dodatu-vrednost--21');
  const after=await read(); assert.deepEqual(after.journals,before.journals); assert.deepEqual(after.drafts,before.drafts);
  await selectFirm.selectOption(other); await page.getByText('No fiscal year',{exact:false}).waitFor();
  await panel.locator('summary').first().click();
  assert.equal(await panel.getByLabel('Poreski režim u primeru').inputValue(),'');
  assert.equal(await panel.getByLabel('Dokaz režima za primer').inputValue(),'');
  await selectFirm.selectOption(firm);
  await page.getByRole('combobox',{name:/^Fiscal year/}).selectOption(year);
  await page.getByRole('button',{name:'New journal',exact:true}).waitFor();
  console.log('PASS: TAX-01 source matrix, exact examples, input-deduction separation, classification, advance/future guards, no ledger writes and firm isolation.');
};
